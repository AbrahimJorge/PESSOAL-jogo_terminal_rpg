def format_name(name):
    """Garante que o nome ocupe exatamente 7 caracteres para não quebrar a arte."""
    if len(name) > 7:
        return name[:7]
    return name.center(7)

def format_enemy_tag(base_name, hp, width, pad_char=' '):
    tag = f"{base_name} - HP {hp}" if hp is not None else base_name
    return tag.center(width, pad_char)

